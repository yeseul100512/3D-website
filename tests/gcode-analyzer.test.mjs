test('analyzeGcode streams a Blob and reports progress', async () => {
  const seen = [];
  const [r] = await analyzeGcode(new Blob([BAMBU]), { onProgress: (p) => seen.push(p) });
  assert.equal(r.plate, null);
  near(r.total.measuredMm, 50);
  assert.equal(seen.at(-1), 1);
});

test('files that are not G-code give a coded error', async () => {
  await assert.rejects(analyzeGcode(new Blob(['Shopping list: milk, eggs.\n; a comment\n'])), fails('no_moves'));
  await assert.rejects(analyzeGcode(new Blob([new Uint8Array([1, 2, 0, 0, 5, 6, 7, 8])])), fails('not_text'));
  await assert.rejects(analyzeGcode(new Blob(['GCDE', new Uint8Array(20)])), fails('bgcode'));
  await assert.rejects(analyzeGcode(zipStore([{ name: '3D/3dmodel.model', data: '<model/>' }])), fails('no_plate'));
  await assert.rejects(analyzeGcode(new Blob(['PK\x03\x04 not really a zip'])), (e) => e.code === 'bad_zip');
});

const SLICE_INFO = `<?xml version="1.0" encoding="UTF-8"?>
<config>
  <plate>
    <metadata key="index" value="1"/>
    <metadata key="prediction" value="4200"/>
    <metadata key="weight" value="0.15"/>
    <filament id="1" type="PLA" color="#000000" used_m="0.05" used_g="0.15"/>
  </plate>
  <plate>
    <metadata key="index" value="2"/>
    <metadata key="prediction" value="60"/>
    <metadata key="weight" value="1.00"/>
  </plate>
</config>`;

test('.gcode.3mf: every plate, slice_info.config, whatever the file is called', async () => {
  const zip = zipStore([
    { name: 'Metadata/plate_2.gcode', data: 'M83\nG1 X1 E7\n' },
    { name: 'Metadata/slice_info.config', data: SLICE_INFO },
    { name: 'Metadata/plate_1.gcode', data: BAMBU },
    { name: 'Metadata/plate_1.gcode.md5', data: 'x' },
  ]);
  const plates = await analyzeGcode(zip);
  assert.deepEqual(plates.map((p) => p.plate), [1, 2]);
  assert.equal(plates[0].total.g, 0.15);
  assert.deepEqual(plates[0].sliceInfo, { seconds: 4200, g: 0.15, filaments: [{ slot: 1, type: 'PLA', colour: '#000000', mm: 50, g: 0.15 }] });
  near(plates[1].total.measuredMm, 7);
  assert.equal(plates[1].sliceInfo.g, 1);
  assert.deepEqual(Object.keys(parseSliceInfo(SLICE_INFO)), ['1', '2']);
});

