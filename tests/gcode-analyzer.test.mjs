test('Bambu totals without a "; filament:" line go to the extruders that were used', () => {
  const head = (len, g) => `; BambuStudio 01.08.00.00\n; total filament length [mm] : ${len}\n; total filament weight [g] : ${g}\n; filament_density: 1.24,1.27,1.04\n; filament_type = PLA;PETG;ABS\nM83\n`;
  const one = scan(head('1000.00', '3.03') + 'T1\nG1 X10 E1000\n');
  assert.deepEqual(one.filaments.map((f) => [f.slot, f.type, f.mm, f.g, f.measuredMm]), [[2, 'PETG', 1000, 3.03, 1000]]);
  near(one.total.mm, 1000);
  near(one.total.g, 3.03);
  const two = scan(head('100.00,50.00', '0.30,0.13') + 'T0\nG1 X10 E100\nT2\nG1 X20 E50\n');
  assert.deepEqual(two.filaments.map((f) => [f.slot, f.type, f.mm, f.measuredMm]), [[1, 'PLA', 100, 100], [3, 'ABS', 50, 50]]);
  near(two.total.mm, 150);
  assert.ok(!codes(two).includes('mismatch'));
});

test('layer height comes from the setting, not from the last per-layer marker', () => {
  const r = scan('; layer_height = 0.2\nM83\n; LAYER_HEIGHT: 0.2\nG1 X1 E1\n; LAYER_HEIGHT: 0.08\nG1 X2 E1\n');
  assert.equal(r.layerHeight, 0.2);
  assert.equal(scan(';Layer height: 0.3\nM83\nG1 X1 E1\n').layerHeight, 0.3); // Cura
});

