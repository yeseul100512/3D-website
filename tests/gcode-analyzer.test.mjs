test('Bambu header, relative E, features, retraction not counted', () => {
  const r = scan(BAMBU);
  assert.deepEqual(r.slicer, { name: 'Bambu Studio', version: '02.08.02.61' });
  assert.equal(r.printer, 'Bambu Lab P2S');
  assert.deepEqual(r.time, { seconds: 4200, model: 3723 });
  assert.equal(r.layers, 2);
  assert.equal(r.layersFrom, 'header');
  assert.equal(r.layerHeight, 0.2);
  near(r.maxZ, 0.4);
  assert.equal(r.nozzleTemp, 220); // from the config, not the 250 °C of the start G-code
  assert.equal(r.bedTemp, 55);
  assert.equal(r.filamentChanges, 0); // T65535 is not a tool
  assert.equal(r.filaments.length, 1);
  const f = r.filaments[0];
  assert.deepEqual([f.slot, f.type, f.colour, f.density, f.costPerKg], [1, 'PLA', '#000000', 1.26, 19.99]);
  assert.equal(f.mm, 50);
  near(f.cm3, 0.12026); // Bambu's "cm^3" line is really mm^3
  assert.equal(f.g, 0.15);
  near(f.measuredMm, 50);
  assert.deepEqual(r.features.map((x) => [x.key, Math.round(x.mm)]), [['sparse_infill', 30], ['outer_wall', 20]]);
  near(r.features[0].share, 0.6);
  assert.deepEqual(codes(r), []);
});

test('the result does not depend on how the text is cut into chunks', () => {
  assert.deepEqual(scan(BAMBU, 7), scan(BAMBU));
  assert.deepEqual(scan(BAMBU.replace(/\n/g, '\r\n'), 13), scan(BAMBU));
});

